"""Append-only call ledger + deterministic settlement against SPY.

calls.jsonl is never edited. settlements.jsonl and TRACK_RECORD.md are
regenerated from scratch on every `settle`, so they're always reproducible
from calls.jsonl + market prices.
"""

from __future__ import annotations

import json
from bisect import bisect_left
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Callable

HORIZONS = (63, 126, 252)  # ~3, 6, 12 months of trading days
LIVE_WINDOW_DAYS = 5       # a call is "live" only if made within this many days of its as-of date

Series = dict  # {"dates": [...], "close": [...]}


def make_call(metrics: dict, today: date | None = None) -> dict:
    today = today or date.today()
    asof = metrics["asof"]
    mode = "live" if (today - date.fromisoformat(asof)).days <= LIVE_WINDOW_DAYS else "backfill"
    return {
        "id": f"{metrics['ticker']}-{asof}-{metrics['rules']['version']}",
        "ticker": metrics["ticker"],
        "asof": asof,
        "price": metrics["price"]["price"],
        "action": metrics["action"]["final"],
        "raw_action": metrics["action"]["raw"],
        "score": metrics["score"]["total"],
        "rules_version": metrics["rules"]["version"],
        "rules_sha256": metrics["rules"]["sha256"],
        "generator": metrics.get("generator"),
        "mode": mode,
        "recorded_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }


def read_calls(ledger_dir: Path) -> list[dict]:
    p = Path(ledger_dir) / "calls.jsonl"
    if not p.exists():
        return []
    return [json.loads(line) for line in p.read_text(encoding="utf-8").splitlines() if line.strip()]


def record(metrics: dict, ledger_dir: Path, today: date | None = None) -> tuple[dict, bool]:
    """Append a call. Idempotent on id. Returns (call, was_new)."""
    call = make_call(metrics, today)
    existing = {c["id"] for c in read_calls(ledger_dir)}
    if call["id"] in existing:
        return call, False
    Path(ledger_dir).mkdir(parents=True, exist_ok=True)
    with open(Path(ledger_dir) / "calls.jsonl", "a", encoding="utf-8") as f:
        f.write(json.dumps(call) + "\n")
    return call, True


def settle_one(call: dict, px: Series, bench: Series, horizon: int) -> dict | None:
    """Excess return of the stock vs benchmark over `horizon` trading days after asof.

    Entry uses the first bar on/after asof in the *freshly fetched* adjusted
    series (not the recorded price), so dividends/splits are handled
    consistently on both legs. Returns None while the horizon is still open.
    """
    i = bisect_left(px["dates"], call["asof"])
    j = bisect_left(bench["dates"], call["asof"])
    if i + horizon >= len(px["dates"]) or j + horizon >= len(bench["dates"]):
        return None
    ret = px["close"][i + horizon] / px["close"][i] - 1
    bret = bench["close"][j + horizon] / bench["close"][j] - 1
    excess = ret - bret
    hit = {"BUY": excess > 0, "AVOID": excess < 0}.get(call["action"])  # HOLD claims no edge
    return {
        "id": call["id"], "ticker": call["ticker"], "action": call["action"], "mode": call["mode"],
        "rules_version": call["rules_version"], "horizon": horizon,
        "entry_date": px["dates"][i], "exit_date": px["dates"][i + horizon],
        "return": round(ret, 6), "benchmark_return": round(bret, 6),
        "excess": round(excess, 6), "hit": hit,
    }


def settle_all(calls: list[dict], fetch: Callable[[str, str], Series], benchmark: str = "SPY") -> list[dict]:
    if not calls:
        return []
    start = (date.fromisoformat(min(c["asof"] for c in calls)) - timedelta(days=7)).isoformat()
    cache: dict[str, Series] = {}

    def series(t):
        if t not in cache:
            cache[t] = fetch(t, start)
        return cache[t]

    rows = []
    for c in sorted(calls, key=lambda c: (c["asof"], c["ticker"])):
        for h in HORIZONS:
            r = settle_one(c, series(c["ticker"]), series(benchmark), h)
            if r:
                rows.append(r)
    return rows


def track_record_md(calls: list[dict], rows: list[dict]) -> str:
    out = ["# Track record", "",
           "Generated by `stockledger settle`. Hit = BUY beat SPY, or AVOID lagged SPY, over the horizon. "
           "HOLD calls claim no edge and are excluded from hit rate.", ""]
    for mode, title in (("live", "Live calls (made in real time)"),
                        ("backfill", "Backfilled calls (point-in-time-ish replay, NOT forward evidence)")):
        mc = [c for c in calls if c["mode"] == mode]
        mr = [r for r in rows if r["mode"] == mode]
        out += [f"## {title}", "", f"Calls recorded: **{len(mc)}**", ""]
        if not mc:
            out += ["_None yet._", ""]
            continue
        if not mr:
            out += ["_No call has reached its first horizon yet._", ""]
            continue
        out += ["| Horizon | Action | Settled | Hit rate | Avg excess vs SPY |", "|---|---|---|---|---|"]
        for h in HORIZONS:
            for act in ("BUY", "AVOID", "HOLD"):
                rs = [r for r in mr if r["horizon"] == h and r["action"] == act]
                if not rs:
                    continue
                hits = [r["hit"] for r in rs if r["hit"] is not None]
                hr = f"{sum(hits) / len(hits):.0%}" if hits else "-"
                avg = sum(r["excess"] for r in rs) / len(rs)
                out.append(f"| {h}d | {act} | {len(rs)} | {hr} | {avg:+.1%} |")
        pending = len(mc) * len(HORIZONS) - len(mr)
        out += ["", f"Pending (horizon not reached yet): {pending}", ""]
    return "\n".join(out) + "\n"


def write_settlement(ledger_dir: Path, fetch: Callable[[str, str], Series]) -> tuple[int, int]:
    calls = read_calls(ledger_dir)
    rows = settle_all(calls, fetch)
    d = Path(ledger_dir)
    d.mkdir(parents=True, exist_ok=True)
    (d / "settlements.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows), encoding="utf-8")
    (d / "TRACK_RECORD.md").write_text(track_record_md(calls, rows), encoding="utf-8")
    return len(calls), len(rows)


def yfinance_closes(ticker: str, start: str) -> Series:
    import yfinance as yf
    h = yf.Ticker(ticker).history(start=start, auto_adjust=True)
    return {"dates": [d.strftime("%Y-%m-%d") for d in h.index], "close": [float(x) for x in h["Close"]]}
